
import logging
import time

from retrieval.hybrid.retrieval import retrieve_hybrid_schemes

logger = logging.getLogger(__name__)


def capture_hybrid_retrieval(
    query,
    discovery_db,
    bm25_retriever,
    cohere_client,
    retrieval_k=30,
    rrf_k=60,
    top_n=10,
):
    try:
        start = time.perf_counter()

        # Execute the complete hybrid pipeline only once.
        result = retrieve_hybrid_schemes(
            query=query,
            discovery_db=discovery_db,
            bm25_retriever=bm25_retriever,
            cohere_client=cohere_client,
            retrieval_k=retrieval_k,
            rrf_k=rrf_k,
            top_n=top_n,
        )

        stages = {
            "dense": result["dense_results"],
            "bm25": result["bm25_results"],
            "rrf": result["rrf_results"],
            "cohere": (
                result["reranked_results"]
                if result["rerank_status"] == "success"
                else []
            ),
        }

        # Collect ranks from every retrieval stage.
        rank_lookup = {
            stage: {
                str(item["scheme_id"]): item.get("rank")
                for item in schemes
                if item.get("scheme_id")
            }
            for stage, schemes in stages.items()
        }

        # Reuse profiles already generated by hybrid retrieval.
        candidates = []

        for profile in result["scheme_profiles"]:
            scheme_id = str(profile["scheme_id"])

            candidates.append({
                "scheme_id": scheme_id,
                "text": profile["text"],
                "stage_ranks": {
                    stage: ranks[scheme_id]
                    for stage, ranks in rank_lookup.items()
                    if scheme_id in ranks
                },
            })

        logger.info(
            "Retrieval captured | candidates=%d | latency=%.2fs",
            len(candidates),
            time.perf_counter() - start,
        )

        return {
            "query": query,
            "stages": stages,
            "candidates": candidates,
            "final_method": result["final_method"],
            "rerank_status": result["rerank_status"],
        }

    except Exception:
        logger.exception("Retrieval capture failed | query=%s", query)
        raise
